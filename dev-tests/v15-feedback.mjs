import assert from 'node:assert/strict';
import { build } from 'esbuild';
const bundle = await build({ stdin: { contents: 'export * from "./src/event-status"; export * from "./src/fight-progress"; export * from "./src/spawn-keys";', resolveDir: process.cwd() }, bundle: true, format: 'esm', platform: 'node', write: false });
const { timerStatus, countStatus, healthStatus, sagaStatus, krakenFightAdvantage, FeedbackGate, SpawnKeyRepeater } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].contents).toString('base64')}`);
const saga = { kind: 'bloom', born: 10, until: 50, count: 900, peak: 901, total: 1000 };
assert.deepEqual(sagaStatus(saga, 20, null), {kind:'timer', progress:.75, counter:'30s'});
assert.equal(sagaStatus({...saga,until:70},20,null).counter,'50s','extensions use the live deadline');
assert.equal(timerStatus(10,50,55).progress,0);
assert.equal(timerStatus(10,50,55).counter,'0s');
assert.equal(sagaStatus({...saga,kind:'meteor'},20,null).kind,'timer');
assert.deepEqual(countStatus(4,8,'resolved'),{kind:'count',progress:.5,counter:'4 of 8 resolved'});
assert.equal(sagaStatus({...saga,kind:'migration',count:3,total:10},20,null).kind,'count');
assert.equal(healthStatus(8,16).progress,.5);
const k={state:'wrap',stateAt:10,wrapFor:10,lunging:false,coiled:true,winner:'kraken',tilt:0,maul:false};
assert.ok(krakenFightAdvantage(k,15)>0);
assert.ok(krakenFightAdvantage({...k,winner:'mega'},15)<0);
assert.ok(krakenFightAdvantage({...k,winner:'mega',tilt:1},10)>0,'live intervention can reverse displayed advantage');
assert.equal(krakenFightAdvantage({...k,lunging:true},15),null);
assert.equal(krakenFightAdvantage({...k,maul:true,biteAt:undefined},15),null);
assert.equal(sagaStatus({...saga,kind:'clash'},15,{...k,state:'flee',rechallengeAt:20}).counter,'re-engaging');
assert.equal(sagaStatus({...saga,kind:'clash'},15,{...k,state:'flee'}).counter,'retreating');
assert.equal(sagaStatus({...saga,kind:'clash'},15,k).kind,'advantage');
const gate=new FeedbackGate();
assert.equal(gate.take('limit:mega',0),1);
assert.equal(gate.take('limit:mega',1),null);
assert.equal(gate.take('limit:mega',2999),null);
assert.equal(gate.take('limit:mega',3000),4,'suppressed repeats contribute to grouped count');
assert.equal(gate.take('limit:kraken',3000),1,'different event groups remain independent');
assert.equal(gate.take('limit:mega',24000),1,'a later burst starts a new count');
const keys=new SpawnKeyRepeater();
assert.equal(keys.accept('A',false,0),true);
assert.equal(keys.accept('a',true,249),false);
assert.equal(keys.accept('a',true,250),true);
assert.equal(keys.accept('a',true,251),false);
keys.release('A'); assert.equal(keys.accept('a',false,252),true);
assert.equal(keys.accept('m',true,1000),false,'boss keys do not repeat');
keys.clear(); assert.equal(keys.accept('a',false,1001),true);
console.log('PASS: v1.5 event status, advantage, command grouping and held lightning');

