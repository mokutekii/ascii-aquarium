import assert from 'node:assert/strict';
import { build } from 'esbuild';
const bundle = await build({ stdin: { contents: 'export { World } from "./src/world"; export { AsciiRenderer } from "./src/renderer";', resolveDir: process.cwd() }, bundle: true, format: 'esm', platform: 'node', write: false });
const { World, AsciiRenderer } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].contents).toString('base64')}`);
process.on('uncaughtException', error => { console.error(error.message); process.exitCode = 1; });
const make = () => { const w = new World([{ kind: 'classic', size: 0.8 }], 5); w.resize(1800, 1200, 13, 19); w.settings.events = 'off'; return w; };
const w = make();
const f = w.fish[0]; Object.assign(f, { x: 1150, y: 600, vx: 0, vy: 0, alive: true });
w.fish = [f]; w.jellies = [{ x: 1100, y: 600, size: 20, phase: 0, drift: 0, hue: 0 }];
w.meteorImpact(900, 600);
assert.ok(f.alive && f.vx > 0 && f.alarm === 1, 'pressure reaches beyond the lethal core');
assert.ok(w.jellies[0].vx > 0, 'meteor pressure throws jellyfish');
assert.ok(w.bombs.some(b => b.meteor && b.r > 300), 'meteor gets a broad pressure ring');
assert.equal(w.lastMeteorAt, w.time);
const whirl = { x: 900, y: 600, r: 150, born: 0, until: 20, dir: 1, rippleAt: 0 };
w.time = 5;
const before = { x: whirl.x, y: whirl.y, r: whirl.r };
w.moveWhirl(whirl, 1);
assert.notDeepEqual({ x: whirl.x, y: whirl.y, r: whirl.r }, before, 'funnels drift and breathe');
w.mess = [{ x: whirl.x + 100, y: whirl.y, vx: 0, vy: 0, born: 0, glyph: '#', rgb: '255,255,255' }];
const scrapX = w.mess[0].x; const jellyX = w.jellies[0].x;
w.spawnMegalodon(); w.spawnKraken(); w.spawnLeviathan();
const titanState = () => JSON.stringify([w.sharks.filter(s => s.mega).map(s => [...s.nodes]), w.kraken, w.leviathan]);
const titans = titanState();
w.pullWhirlObjects(whirl, 1);
assert.ok(w.mess[0].x < scrapX && w.jellies[0].x < jellyX, 'scrap and jellyfish spiral inward');
assert.equal(titanState(), titans, 'whirlpool object pull does not move titans');
// The same funnel affects craft, large wildlife and projectiles according to weight.
const current = make(); current.time = 5;
current.spawnSub(); current.spawnUfo(); current.spawnWhale(true);
const sb = current.subs[0], saucer = current.ufos[0], whale = current.whales[0];
const funnel = { x: 900, y: 600, r: 150, born: 0, until: 20, dir: 1, rippleAt: 0 };
for (const actor of [sb, saucer, whale]) Object.assign(actor, { x: 1000, y: 600 });
saucer.hy = 600; saucer.beamX = 1000;
whale.spine = [{ x: 1000, y: 600 }, { x: 900, y: 600 }];
current.attackDrones = [{ id: 1, x: 1000, y: 600, hp: 3, stunned: 0, nextShot: 100 }];
current.torpedoes = [{ x: 1000, y: 600, vx: 200, vy: 0, born: 5, trail: [{ x: 980, y: 600 }] }];
current.pullWhirlObjects(funnel, .1);
const moved = actor => Math.hypot(actor.x - 1000, actor.y - 600);
assert.ok(moved(current.attackDrones[0]) > moved(saucer) && moved(saucer) > moved(sb) && moved(sb) > moved(whale), 'drones drift most, UFOs and subs resist, whales barely shift');
const gentleDroneDrift = moved(current.attackDrones[0]);
assert.equal(saucer.hy, saucer.y, 'hover anchor moves with the UFO');
assert.equal(saucer.beamX, saucer.x, 'emitter moves with the UFO');
assert.equal(whale.spine[0].x, whale.x, 'whale body moves with its head');
assert.ok(current.torpedoes[0].vy > 0, 'torpedoes bend around the current');
assert.ok(Math.abs(Math.hypot(current.torpedoes[0].vx, current.torpedoes[0].vy) - 200) < .001, 'current bends a torpedo without accelerating it');
assert.equal(current.torpedoes[0].trail[0].x, 980, 'old projectile wake stays in place');
sb.seizedByKraken = true; saucer.held = true;
const held = [sb.x, sb.y, saucer.x, saucer.y];
current.pullWhirlObjects(funnel, .1, true);
assert.deepEqual([sb.x, sb.y, saucer.x, saucer.y], held, 'currents do not tear held hulls out of kraken arms');
Object.assign(current.attackDrones[0], { x: 1000, y: 600 });
current.pullWhirlObjects(funnel, .1, true);
assert.ok(moved(current.attackDrones[0]) > gentleDroneDrift * 1.49, 'maelstroms use the same current with stronger craft drag');
for (const mode of ['off', 'normal', 'busy']) {
  const g = make(); g.settings.events = mode; g.nextEventAt = Infinity; g.time = 7;
  g.stepEvents(1 / 60);
  assert.equal(g.diverQueue.length > 0, mode === 'busy', 'extra diver timer is busy-only');
}
const capped = make(); capped.diverCap = 2;
capped.spawnDivers(true); assert.ok(capped.diverQueue.length <= 2, 'batch respects remaining diver capacity');
const noop = () => {};
const context = new Proxy({}, { get: (obj, key) => obj[key] ?? (String(key).startsWith('create') ? () => ({ addColorStop: noop }) : noop), set: (obj,key,value) => (obj[key] = value, true) });
globalThis.document = { createElement: () => ({ getContext: () => context }) };
const r = new AsciiRenderer({ style: {}, getContext: () => context }); r.resize(1800,1200,1);
const points = []; r.painter = () => ({ put: (x,y,glyph,color) => points.push({x,y,glyph,color}), flush: noop });
const g = make(); g.spawnUfo(); const u = g.ufos[0]; Object.assign(g.fish[0],{x:900,y:500}); Object.assign(u, { x: 900, y: 100, beamX: 900, state: 'beam', aim:{x:900,y:500}, beamTarget:g.fish[0] });
g.lighting = 'night'; r.drawOneUfo(g,u);
const beam = points.filter(p => p.color.startsWith('rgba(85,255,120') || p.color.startsWith('rgba(185,255,195'));
assert.ok(Math.max(...beam.map(p => p.y)) > 500 && Math.max(...beam.map(p=>p.y)) <= 525, 'tractor trail follows the capture target depth');
assert.ok(beam.every(p=>Math.abs(p.x-u.beamX)<=55), 'tractor column never bulges wider than its capture width');
assert.ok(beam.some(p => p.color.includes('0.92')), 'night strengthens the green beam edges');
console.log('PASS: meteor pressure, drifting whirlpools, light-object pull, titan resistance, busy divers, population cap and full night tractor trail');
